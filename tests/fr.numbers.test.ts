import { describe, it, expect } from 'vitest'
import { numberWordsToDigits as n2d, hasNumberWord, parseNumberWord } from '@/lang/fr/numbers'

describe('French number words', () => {
  it('converts 0–69', () => {
    expect(n2d('zéro')).toBe('0')
    expect(n2d('quinze')).toBe('15')
    expect(n2d("J'ai quinze ans.")).toBe("J'ai 15 ans.")
    expect(n2d('seize')).toBe('16')
    expect(n2d('dix-sept')).toBe('17')
    expect(n2d('dix-huit')).toBe('18')
    expect(n2d('dix-neuf')).toBe('19')
    expect(n2d('vingt')).toBe('20')
    expect(n2d('vingt et un')).toBe('21')
    expect(n2d('vingt-et-un')).toBe('21')
    expect(n2d('vingt-deux')).toBe('22')
    expect(n2d('trente et une pages')).toBe('31 pages')
    expect(n2d('quarante-cinq')).toBe('45')
    expect(n2d('cinquante-neuf')).toBe('59')
    expect(n2d('soixante-six')).toBe('66')
  })
  it('converts 70–99 the French way', () => {
    expect(n2d('soixante-dix')).toBe('70')
    expect(n2d('soixante et onze')).toBe('71')
    expect(n2d('soixante-et-onze')).toBe('71')
    expect(n2d('soixante-douze')).toBe('72')
    expect(n2d('soixante-dix-sept')).toBe('77')
    expect(n2d('soixante-dix-neuf')).toBe('79')
    expect(n2d('quatre-vingts')).toBe('80')
    expect(n2d('quatre-vingt-un')).toBe('81')
    expect(n2d('quatre-vingt-une')).toBe('81')
    expect(n2d('quatre-vingt-deux')).toBe('82')
    expect(n2d('quatre-vingt-dix')).toBe('90')
    expect(n2d('quatre-vingt-onze')).toBe('91')
    expect(n2d('quatre-vingt-dix-sept')).toBe('97')
    expect(n2d('quatre-vingt-dix-neuf')).toBe('99')
  })
  it('understands Belgian and Swiss septante, huitante, octante, nonante', () => {
    expect(n2d('septante')).toBe('70')
    expect(n2d('septante et un')).toBe('71')
    expect(n2d('septante-deux')).toBe('72')
    expect(n2d('huitante')).toBe('80')
    expect(n2d('octante-quatre')).toBe('84')
    expect(n2d('nonante')).toBe('90')
    expect(n2d('nonante-neuf')).toBe('99')
  })
  it('converts hundreds, thousands and millions', () => {
    expect(n2d('cent')).toBe('100')
    expect(n2d('cent un')).toBe('101')
    expect(n2d('cent vingt')).toBe('120')
    expect(n2d('deux cents')).toBe('200')
    expect(n2d('deux cent trois')).toBe('203')
    expect(n2d('deux-cent-trois')).toBe('203')
    expect(n2d('trois cent quatre-vingts')).toBe('380')
    expect(n2d('neuf cent quatre-vingt-dix-neuf')).toBe('999')
    expect(n2d('mille')).toBe('1000')
    expect(n2d('mille deux cents')).toBe('1200')
    expect(n2d('mille neuf cent quatre-vingt-dix-neuf')).toBe('1999')
    expect(n2d('deux mille')).toBe('2000')
    expect(n2d('deux mille vingt-six')).toBe('2026')
    expect(n2d('deux-mille-vingt-six')).toBe('2026')
    expect(n2d('cent mille')).toBe('100000')
    expect(n2d('quatre-vingt mille')).toBe('80000')
    expect(n2d('un million')).toBe('1000000')
    expect(n2d('deux millions')).toBe('2000000')
    expect(n2d('trois millions deux cent mille')).toBe('3200000')
    expect(n2d('neuf cent quatre-vingt-dix-neuf millions neuf cent quatre-vingt-dix-neuf mille neuf cent quatre-vingt-dix-neuf')).toBe('999999999')
    expect(n2d('un milliard')).toBe('1000000000')
  })
  it('keeps the rest of the sentence intact', () => {
    expect(n2d('Il est trois heures et demie.')).toBe('Il est 3 heures et demie.')
    expect(n2d("J'ai deux chiens et trois chats")).toBe("J'ai 2 chiens et 3 chats")
    expect(n2d('Quel âge as-tu ? Quinze.')).toBe('Quel âge as-tu ? 15.')
    expect(n2d('Les Mille et Une Nuits')).toBe('Les 1001 Nuits')
    expect(n2d('trois et quatre')).toBe('3 et 4')
    expect(n2d('cinq - six')).toBe('5 - 6')
  })
  it('never touches the articles un / une', () => {
    expect(n2d('une maison')).toBe('une maison')
    expect(n2d('un chien')).toBe('un chien')
    expect(n2d("J'en ai un.")).toBe("J'en ai un.")
    expect(n2d('un')).toBe('1')
    expect(n2d('une')).toBe('1')
    expect(n2d('trente et un')).toBe('31')
  })
  it('reads "neuf" as nine only where it is a number', () => {
    expect(n2d('neuf')).toBe('9')
    expect(n2d('Il a neuf ans')).toBe('Il a 9 ans')
    expect(n2d('à neuf heures')).toBe('à 9 heures')
    expect(n2d('les neuf')).toBe('les 9')
    expect(n2d('dix-neuf')).toBe('19')
    expect(n2d('un livre neuf')).toBe('un livre neuf')
    expect(n2d('Quoi de neuf ?')).toBe('Quoi de neuf ?')
    expect(n2d('tout neuf')).toBe('tout neuf')
  })
  it('leaves words that only look like numbers', () => {
    expect(n2d('et')).toBe('et')
    expect(n2d('Centre-ville')).toBe('Centre-ville')
    expect(n2d('septembre')).toBe('septembre')
    expect(n2d('onzième')).toBe('onzième')
    expect(n2d('trois-quarts')).toBe('3-quarts')
  })
  it('parses whole number phrases', () => {
    expect(parseNumberWord('quatre-vingt-dix-sept')).toBe(97)
    expect(parseNumberWord('cinquante mille')).toBe(50000)
    expect(parseNumberWord('soixante et onze')).toBe(71)
    expect(parseNumberWord('bonjour')).toBeUndefined()
    expect(parseNumberWord('deux chats')).toBeUndefined()
  })
  it('detects number words', () => {
    expect(hasNumberWord("j'ai quinze ans")).toBe(true)
    expect(hasNumberWord("j'ai une maison")).toBe(false)
    expect(hasNumberWord('un livre neuf')).toBe(false)
    expect(hasNumberWord('quatre-vingts')).toBe(true)
  })
})
