import { describe, it, expect } from 'vitest'
import { numberWordsToDigits, hasNumberWord, parseNumberWord } from '@/lang/it/numbers'

describe('Italian number words', () => {
  it('converts simple numbers and compounds', () => {
    expect(numberWordsToDigits('quindici')).toBe('15')
    expect(numberWordsToDigits('Ho quindici anni.')).toBe('Ho 15 anni.')
    expect(numberWordsToDigits('diciassette')).toBe('17')
    expect(numberWordsToDigits('diciannove')).toBe('19')
    expect(numberWordsToDigits('venti')).toBe('20')
    expect(numberWordsToDigits('ventuno')).toBe('21')
    expect(numberWordsToDigits('ventun anni')).toBe('21 anni')
    expect(numberWordsToDigits('ventitré')).toBe('23')
    expect(numberWordsToDigits('ventitre')).toBe('23')
    expect(numberWordsToDigits('ventotto')).toBe('28')
    expect(numberWordsToDigits('trentuno')).toBe('31')
    expect(numberWordsToDigits('trentotto')).toBe('38')
    expect(numberWordsToDigits('novantanove')).toBe('99')
    expect(numberWordsToDigits('cento')).toBe('100')
    expect(numberWordsToDigits('centouno')).toBe('101')
    expect(numberWordsToDigits('centotto')).toBe('108')
    expect(numberWordsToDigits('centottanta')).toBe('180')
    expect(numberWordsToDigits('duecento')).toBe('200')
    expect(numberWordsToDigits('duecentoquarantadue persone')).toBe('242 persone')
    expect(numberWordsToDigits('novecentonovantanove')).toBe('999')
    expect(numberWordsToDigits('mille')).toBe('1000')
    expect(numberWordsToDigits('milleduecento')).toBe('1200')
    expect(numberWordsToDigits('millenovecentonovantanove')).toBe('1999')
    expect(numberWordsToDigits('duemila')).toBe('2000')
    expect(numberWordsToDigits('duemilaventisei')).toBe('2026')
    expect(numberWordsToDigits('centomila')).toBe('100000')
    expect(numberWordsToDigits('un milione')).toBe('1000000')
    expect(numberWordsToDigits('due milioni trecentomila')).toBe('2300000')
    expect(numberWordsToDigits('tre miliardi')).toBe('3000000000')
    expect(numberWordsToDigits('zero')).toBe('0')
  })
  it('keeps the rest of the sentence intact', () => {
    expect(numberWordsToDigits('Sono le tre e mezza.')).toBe('Sono le 3 e mezza.')
    expect(numberWordsToDigits('Ho due cani e tre gatti')).toBe('Ho 2 cani e 3 gatti')
    expect(numberWordsToDigits('Quanti anni hai? Quindici.')).toBe('Quanti anni hai? 15.')
    expect(numberWordsToDigits('un milione e mezzo')).toBe('1000000 e mezzo')
  })
  it('never touches articles or a lone uno inside a sentence', () => {
    expect(numberWordsToDigits('una casa')).toBe('una casa')
    expect(numberWordsToDigits('un cane')).toBe('un cane')
    expect(numberWordsToDigits('uno studente')).toBe('uno studente')
    expect(numberWordsToDigits('Ne ho uno.')).toBe('Ne ho uno.')
    expect(numberWordsToDigits('uno')).toBe('1')
    expect(numberWordsToDigits('trentuno')).toBe('31')
  })
  it('reads "sei" as six only where it is a number', () => {
    expect(numberWordsToDigits('sei')).toBe('6')
    expect(numberWordsToDigits('Sono le sei.')).toBe('Sono le 6.')
    expect(numberWordsToDigits('Ho sei anni')).toBe('Ho 6 anni')
    expect(numberWordsToDigits('sei libri')).toBe('6 libri')
    expect(numberWordsToDigits('Tu sei italiano.')).toBe('Tu sei italiano.')
    expect(numberWordsToDigits('Sei stanca?')).toBe('Sei stanca?')
    expect(numberWordsToDigits('Sei mai stato a Roma?')).toBe('Sei mai stato a Roma?')
    expect(numberWordsToDigits('ventisei')).toBe('26')
    expect(numberWordsToDigits('seicento')).toBe('600')
  })
  it('does not fold e between two numbers or words that only look like numbers', () => {
    expect(numberWordsToDigits('tre e tre')).toBe('3 e 3')
    expect(numberWordsToDigits('e')).toBe('e')
    expect(numberWordsToDigits('Milano è bella')).toBe('Milano è bella')
    expect(numberWordsToDigits('treno')).toBe('treno')
    expect(numberWordsToDigits('ottobre')).toBe('ottobre')
  })
  it('parses single number words', () => {
    expect(parseNumberWord('quattrocentoventitré')).toBe(423)
    expect(parseNumberWord('cinquantamila')).toBe(50000)
    expect(parseNumberWord('ciao')).toBeUndefined()
  })
  it('detects number words', () => {
    expect(hasNumberWord('ho quindici anni')).toBe(true)
    expect(hasNumberWord('ho una casa')).toBe(false)
    expect(hasNumberWord('tu sei italiano')).toBe(false)
    expect(hasNumberWord('le sei')).toBe(true)
  })
})
