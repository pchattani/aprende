import { describe, it, expect } from 'vitest'
import { explainConfig as C } from '@/lang/fr/explain'
import type { VocabEntry } from '@/engine/schema'

const noun = (lemma: string, gender: 'm' | 'f'): VocabEntry => ({ id: `w.${lemma}`, lemma, pos: 'noun', gender, en: ['x'], level: 'a1', tags: [] }) as VocabEntry
const pair = (a: string, b: string) => C.pairs.find((p) => p.a.has(a) && p.b.has(b))

describe('French explain config', () => {
  it('names the language and its marks', () => {
    expect(C.languageName).toBe('French')
    expect(C.marks).toBe('accents')
    expect(C.negation).toBe('ne')
  })
  it('lists articles, contractions and prepositions', () => {
    for (const a of ['le', 'la', "l'", 'les', 'un', 'une', 'des', 'du', 'au', 'aux']) expect(C.articles.has(a), a).toBe(true)
    for (const p of ['à', 'de', 'en', 'dans', 'sur', 'avec', 'pour', 'par', 'chez', 'depuis', 'pendant']) expect(C.preps.has(p), p).toBe(true)
    expect(C.articles.has('de')).toBe(false)
  })
  it('never treats subject pronouns as optional', () => {
    for (const s of ['je', 'tu', 'il', 'elle', 'on', 'nous', 'vous', 'ils', 'elles']) expect(C.subjects.has(s), s).toBe(false)
    expect(C.subjects.size).toBe(0)
    expect(C.notAfterSubject.has('et')).toBe(true)
    expect(C.emphatic.get('à moi')).toBe('me')
    expect(C.emphatic.get('à eux')).toBe('leur')
    for (const p of ['me', "m'", 'te', 'se', "s'", 'le', 'la', "l'", 'les', 'lui', 'leur', 'y', 'en', 'nous', 'vous']) expect(C.objectPronouns.has(p), p).toBe(true)
  })
  it('explains être vs avoir as auxiliaries', () => {
    const p = pair('suis', 'ai')!
    expect(p).toBeDefined()
    expect(p.a.has('sommes')).toBe(true)
    expect(p.a.has('fussent')).toBe(true)
    expect(p.b.has('avions')).toBe(true)
    expect(p.useA('suis')).toMatch(/VANDERTRAMP|pronominal/)
    expect(p.useB('ai')).toMatch(/avoir/)
  })
  it('explains c’est / il est, savoir / connaître, depuis / pendant, à / en, tu / vous', () => {
    expect(pair("c'", 'il')!.useA("c'")).toMatch(/c'est un médecin/)
    expect(pair("c'", 'il')!.useB('il')).toMatch(/il est grand/)
    const sc = pair('sais', 'connais')!
    expect(sc.a.has('savons')).toBe(true)
    expect(sc.b.has('connaissons')).toBe(true)
    expect(sc.useA('sais')).toMatch(/fact|how/)
    expect(sc.useB('connais')).toMatch(/person|place/)
    expect(pair('depuis', 'pendant')!.useA('depuis')).toMatch(/still/)
    expect(pair('pendant', 'depuis')!.useA('pendant')).toMatch(/finished/)
    expect(pair('pendant', 'il')!.useB('il')).toMatch(/il y a/)
    const enA = pair('en', 'à')!
    expect(enA.useA('en')).toMatch(/en France/)
    expect(enA.useB('à')).toMatch(/Paris/)
    expect(enA.useB('au')).toMatch(/au Japon/)
    expect(pair('vous', 'tu')!.useA('vous')).toMatch(/polite/)
    expect(pair('vous', 'tu')!.useB('tu')).toMatch(/friend/)
    expect(pair('de', 'du')!.useA('de')).toMatch(/negation/)
    expect(pair('bien', 'bon')!.useB('bonne')).toMatch(/adjective/)
  })
  it('gives hints for the two parts of the negation, y and en', () => {
    expect(C.missingHint?.('pas', undefined)).toMatch(/ne … pas/)
    expect(C.missingHint?.('ne', 'sais')).toMatch(/ne before the verb/)
    expect(C.missingHint?.("n'", 'ai')).toMatch(/pas/)
    expect(C.missingHint?.('y', 'vais')).toMatch(/j'y vais/)
    expect(C.missingHint?.('en', 'veux')).toMatch(/some/)
    expect(C.missingHint?.('se', 'lève')).toMatch(/pronominal/)
    expect(C.missingHint?.("l'", 'ai')).toMatch(/before the verb/)
    expect(C.missingHint?.('maison', undefined)).toBeUndefined()
  })
  it('explains accents', () => {
    expect(C.accentHint('a', 'à')).toMatch(/has/)
    expect(C.accentHint('à', 'a')).toMatch(/No accent/)
    expect(C.accentHint('ou', 'où')).toMatch(/where/)
    expect(C.accentHint('la', 'là')).toMatch(/there/)
    expect(C.accentHint('sur', 'sûr')).toMatch(/sure/)
    expect(C.accentHint('garcon', 'garçon')).toMatch(/Cedilla/)
    expect(C.accentHint('ète', 'été')).toMatch(/acute/)
    expect(C.accentHint('pére', 'père')).toMatch(/grave/)
    expect(C.accentHint('foret', 'forêt')).toMatch(/forêt/)
  })
  it('describes agreement changes', () => {
    expect(C.agreement('petit', 'petite')).toEqual(['feminine'])
    expect(C.agreement('petite', 'petit')).toEqual(['masculine'])
    expect(C.agreement('petit', 'petits')).toEqual(['plural'])
    expect(C.agreement('petites', 'petite')).toEqual(['singular'])
    expect(C.agreement('petit', 'petites')).toEqual(['feminine', 'plural'])
    expect(C.agreement('heureux', 'heureuse')).toEqual(['feminine'])
    expect(C.agreement('actif', 'actives')).toEqual(['feminine', 'plural'])
    expect(C.agreement('normal', 'normaux')).toEqual(['plural'])
    expect(C.agreement('cher', 'chère')).toEqual(['feminine'])
    expect(C.agreement('allé', 'allées')).toEqual(['feminine', 'plural'])
    expect(C.agreement('rouge', 'rouges')).toEqual(['plural'])
    expect(C.agreement('maison', 'livre')).toEqual([])
  })
  it('explains article choice', () => {
    expect(C.articleHint("l'", noun('ami', 'm'), 'ami', 'le')).toMatch(/vowel/)
    expect(C.articleHint('le', noun('héros', 'm'), 'héros', "l'")).toMatch(/aspirated/)
    expect(C.articleHint('cet', noun('homme', 'm'), 'homme', 'ce')).toMatch(/cet ami/)
    expect(C.articleHint('mon', noun('amie', 'f'), 'amie', 'ma')).toMatch(/mon amie/)
    expect(C.articleHint('du', noun('pain', 'm'), 'pain', 'de')).toMatch(/de \+ le/)
    expect(C.articleHint('au', noun('cinéma', 'm'), 'cinéma', 'à')).toMatch(/à \+ le/)
    expect(C.articleHint('la', noun('maison', 'f'), 'maison', 'le')).toMatch(/feminine/)
    expect(C.articleHint('les', noun('maison', 'f'), 'maisons', 'la')).toMatch(/feminine plural/)
    expect(C.missingArticle('le')).toMatch(/j'aime le café/)
    expect(C.missingArticle('aux')).toMatch(/à \+ les/)
    expect(C.wordOrder).toMatch(/order/)
  })
  it('splits elisions for the feedback diff like the tokenizer', () => {
    expect(C.tokens?.("L'ami est à l'école.")).toEqual(["L'", 'ami', 'est', 'à', "l'", 'école'])
    expect(C.tokens?.("Qu'est-ce que c'est ?")).toEqual(["Qu'", 'est', 'ce', 'que', "c'", 'est'])
    expect(C.tokens?.('L’amie, aujourd’hui')).toEqual(["L'", 'amie', "aujourd'hui"])
    expect(C.tokens?.("J'ai 3 ans")).toEqual(["J'", 'ai', '3', 'ans'])
  })
})
