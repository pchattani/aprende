import { describe, it, expect } from 'vitest'
import { numberWordsToDigits, hasNumberWord } from '@/lang/pt/numbers'

describe('Portuguese number words', () => {
  it('converts simple numbers and compounds', () => {
    expect(numberWordsToDigits('quinze')).toBe('15')
    expect(numberWordsToDigits('Tenho quinze anos.')).toBe('Tenho 15 anos.')
    expect(numberWordsToDigits('dezesseis')).toBe('16')
    expect(numberWordsToDigits('vinte e um livros')).toBe('21 livros')
    expect(numberWordsToDigits('vinte e uma casas')).toBe('21 casas')
    expect(numberWordsToDigits('trinta e cinco')).toBe('35')
    expect(numberWordsToDigits('cento e um')).toBe('101')
    expect(numberWordsToDigits('cento e vinte e três')).toBe('123')
    expect(numberWordsToDigits('duzentas e quarenta e duas pessoas')).toBe('242 pessoas')
    expect(numberWordsToDigits('mil novecentos e noventa e nove')).toBe('1999')
    expect(numberWordsToDigits('mil e quinhentos')).toBe('1500')
    expect(numberWordsToDigits('dois mil e vinte e seis')).toBe('2026')
    expect(numberWordsToDigits('dois milhões e trezentos mil')).toBe('2300000')
    expect(numberWordsToDigits('dois milhões trezentos mil')).toBe('2300000')
    expect(numberWordsToDigits('um milhão de pessoas')).toBe('1000000 de pessoas')
    expect(numberWordsToDigits('cem')).toBe('100')
    expect(numberWordsToDigits('cem mil')).toBe('100000')
    expect(numberWordsToDigits('zero')).toBe('0')
    expect(numberWordsToDigits('quinhentos reais')).toBe('500 reais')
  })
  it('reads Brazilian and European spellings', () => {
    expect(numberWordsToDigits('dezasseis')).toBe('16')
    expect(numberWordsToDigits('dezessete')).toBe('17')
    expect(numberWordsToDigits('dezassete')).toBe('17')
    expect(numberWordsToDigits('dezenove')).toBe('19')
    expect(numberWordsToDigits('dezanove')).toBe('19')
    expect(numberWordsToDigits('catorze')).toBe('14')
    expect(numberWordsToDigits('quatorze')).toBe('14')
    expect(numberWordsToDigits('TRÊS')).toBe('3')
    expect(numberWordsToDigits('tres')).toBe('3')
  })
  it('keeps the rest of the sentence intact', () => {
    expect(numberWordsToDigits('São três e meia.')).toBe('São 3 e meia.')
    expect(numberWordsToDigits('Tenho dois cachorros e três gatos')).toBe('Tenho 2 cachorros e 3 gatos')
    expect(numberWordsToDigits('Quantos anos você tem? Quinze.')).toBe('Quantos anos você tem? 15.')
    expect(numberWordsToDigits('às duas e vinte')).toBe('às 2 e 20')
  })
  it('never touches articles or a lone um inside a sentence', () => {
    expect(numberWordsToDigits('uma casa')).toBe('uma casa')
    expect(numberWordsToDigits('um cachorro')).toBe('um cachorro')
    expect(numberWordsToDigits('Tenho um.')).toBe('Tenho um.')
    expect(numberWordsToDigits('um')).toBe('1')
    expect(numberWordsToDigits('uma')).toBe('1')
    expect(numberWordsToDigits('trinta e um')).toBe('31')
  })
  it('does not fold e between two separate numbers', () => {
    expect(numberWordsToDigits('três e três')).toBe('3 e 3')
    expect(numberWordsToDigits('vinte e')).toBe('20 e')
    expect(numberWordsToDigits('e')).toBe('e')
  })
  it('detects number words', () => {
    expect(hasNumberWord('tenho quinze anos')).toBe(true)
    expect(hasNumberWord('são duzentos reais')).toBe(true)
    expect(hasNumberWord('tenho uma casa')).toBe(false)
    expect(hasNumberWord('um dia')).toBe(false)
  })
})
